/**
 * Generates the VAPID key pair that Web Push identifies this server with.
 *
 *   node scripts/generate-vapid-keys.mjs
 *
 * The public key is handed to the browser so it can create a subscription
 * that only this server can push to; the private key signs the requests to
 * Apple's, Google's and Mozilla's push services. They belong together — a new
 * pair invalidates every subscription the old one created, so generate once
 * and keep the values.
 *
 * Deliberately dependency-free: this has to run on a server that has never
 * installed the app's node_modules, including through
 * `docker run --rm -v "$PWD":/app -w /app node:22-alpine`.
 */
import { generateKeyPairSync } from 'node:crypto'

// VAPID is ECDSA on P-256, and the keys travel as unpadded base64url.
const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' })

const jwk = publicKey.export({ format: 'jwk' })
const privateJwk = privateKey.export({ format: 'jwk' })

const fromBase64Url = (value) => Buffer.from(value, 'base64url')

// The public key goes out as an uncompressed EC point: 0x04 || X || Y.
const publicKeyB64 = Buffer.concat([
  Buffer.from([0x04]),
  fromBase64Url(jwk.x),
  fromBase64Url(jwk.y),
]).toString('base64url')

const privateKeyB64 = fromBase64Url(privateJwk.d).toString('base64url')

console.log(`# ---------------------------------------------------------------
# Generated by: node scripts/generate-vapid-keys.mjs
# Paste these into your .env and set VAPID_SUBJECT to a real address.
# Regenerating invalidates existing subscriptions, so everyone would
# have to re-enable notifications.
#
# On hosted Supabase / Vercel there is no compose file to map the
# public key, so name it NEXT_PUBLIC_VAPID_PUBLIC_KEY there instead.
# ---------------------------------------------------------------
VAPID_PUBLIC_KEY=${publicKeyB64}
VAPID_PRIVATE_KEY=${privateKeyB64}
VAPID_SUBJECT=mailto:you@example.com
`)
